// Builds database/supabase_setup.sql: every migration in order, in one file,
// to paste into Supabase → SQL Editor → Run on a NEW project.
//   node tools/supabase/build_setup_sql.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DIR = join(ROOT, 'database', 'migrations');
const files = readdirSync(DIR).filter(f => f.endsWith('.sql')).sort();
const parts = [`-- ============================================================================
-- Minga Parish Management System — full database setup for Supabase
-- GENERATED by tools/supabase/build_setup_sql.mjs from database/migrations/
-- (${files.join(', ')}). Do not edit by hand: edit the migrations and rebuild.
--
-- How to use: Supabase → SQL Editor → New query → paste this whole file → Run.
-- Run it on the parish's own project. It contains no personal data.
-- ============================================================================
`];
for (const f of files) parts.push(`\n-- >>>>>>>>>>>>>>>>>>>> ${f} >>>>>>>>>>>>>>>>>>>>\n` + readFileSync(join(DIR, f), 'utf8'));
parts.push(`\n-- >>>>>>>>>>>>>>>>>>>> check >>>>>>>>>>>>>>>>>>>>
select 'Database ya parokia iko tayari' as hali,
       (select count(*) from public.org_units where unit_type = 'kigango') as vigango,
       (select count(*) from public.org_units where unit_type = 'jumuiya') as jumuiya,
       (select count(*) from public.contribution_categories) as aina_za_michango;
`);
writeFileSync(join(ROOT, 'database', 'supabase_setup.sql'), parts.join('\n'));
console.log(`database/supabase_setup.sql written from ${files.length} migrations`);
