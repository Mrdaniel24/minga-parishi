"""
Generate docs/WORKBOOK_AUDIT.md (per-sheet inventory) and
docs/WORKSHEET_DEPENDENCIES.md from the inventory JSON produced by
inventory.py-style scanning (sheet stats, formula families, cross-sheet refs).

    python -I tools/migration/build_audit_docs.py <inventory.json>

Only structural facts are written (counts, functions, references, error
counts, classification) — no cell values, so no personal data.
"""
import sys, os, json, re, collections

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
inv = json.load(open(sys.argv[1], encoding='utf-8'))

CLASS = {
    'HOMEBOOK': ('Reference data', 'Parish identity (diocese, parish name, address), receipt labels, list of jumuiya, vigango and the 71 transaction-purpose labels used by every other sheet.'),
    'HOMEDATA': ('Reference data', 'Kigango → jumuiya structure (51 jumuiya in 7 groups), month→column map for Zaka, per-relationship envelope rates (BABA 5,000 … MTOTO 2,000).'),
    'START': ('Legacy template', 'Navigation/start page (hyperlinks only).'),
    'AKAUNTI BOOK-MIAMALA YOTE': ('Financial source data', 'THE LEDGER. One row per receipt: kigango, jumuiya, payer, date, time, purpose, amount (2025 column L / 2026 column M), method, receiver. Rows are grouped in jumuiya blocks (named ranges) and purpose sections, each ending with a subtotal row (SUM) and, for assessed campaigns, WALICHOPANGIWA (target), KIASI BADO (balance) and % YA UTOAJI.'),
    'MIAMALA-YOTE  ': ('Intermediate calculation', 'Receipt-number index: VLOOKUP of every ledger column by receipt number (feeds RISITI).'),
    'MIAMALA-YOTE -SORTING (2)': ('Intermediate calculation', 'Copy of the receipt index used for sorting; 2,850 #VALUE! cells.'),
    'PAROKIA DATA BASE': ('Master data', 'Member register (family no., person no., name, sex, relationship, Zaka flag, age, phone) in jumuiya blocks (named ranges) PLUS hand-typed Zaka Jan–Dec 2025–2028, Mavuno/Ujenzi PANGIWA–TOA–BADO per family, envelope assessments, and SMS text builders.'),
    'MICHANGO-2026 ': ('Pledge data', '2026 assessments per jumuiya for the special campaigns (Makatekista, Mapadri, Askofu, Kristo Mfufuka, Kongamano, Mafrateri, Radio Maria, VIWAWA).'),
    'RISITI': ('Printable form', 'Receipt print-out: VLOOKUP by receipt number + amount-in-words formula (English).'),
    ' SMS ZAKA ,UJ & MAV': ('Intermediate calculation', 'SMS message texts built from the register.'),
    'RIPOTI-UTOAJI <-->RIPOTI-FEDHA ': ('Legacy template', 'Empty divider sheet.'),
    'Sheet1': ('Legacy template', 'Empty.'),
    'Sheet3': ('Intermediate calculation', 'Scratch calculation (1 formula).'),
    'BAHASHA ZA RAFIKI WA PAPA': ('Master data', 'Envelope assignment list (name, phone, envelope no.) — values only, no link to the ledger.'),
    'JUMLA MING & MUGHANGA': ('Intermediate calculation', 'Per-jumuiya totals for Minga & Mughanga feeding REPORT MINGA & MUGH.'),
    'WALIOONGOZ MAVUNO 202 DATA': ('Intermediate calculation', 'Ranking data for top Mavuno contributors.'),
}


def classify(name, s):
    if name in CLASS: return CLASS[name]
    n = name.upper().strip()
    if n.startswith(('FOMU', 'FREE-FOMU')) or 'FOMU' in n: return ('Printable form', 'Collection / entry form for jumuiya leaders.')
    if 'MEMO' in n: return ('Intermediate calculation', 'Per-person memo lines built from the register.')
    if re.search(r'2024|2025', n) and not re.search(r'2026', n): return ('Historical summary', 'Report for a previous year.')
    if n.startswith('BAHASHA') or 'KAPU' in n: return ('Calculated report', 'Envelope distribution/return report per jumuiya (counts typed by hand, amounts typed as sums).')
    if 'MADENI' in n: return ('Calculated report', 'Outstanding balances (debts) per jumuiya / kigango.')
    if s['formulas'] == 0 and s['values'] > 0: return ('Legacy template', 'Static values only.')
    return ('Calculated report', 'Report built by VLOOKUP/SUM over the ledger subtotals and/or the register.')


def fam_list(s, k=6):
    return '; '.join(f"`{f['formula'][:110].replace('|', '¦')}` ×{f['n']}" for f in sorted(s['families'], key=lambda f: -f['n'])[:k])


sheets = inv['sheets']
cls_count = collections.Counter(classify(s['name'], s)[0] for s in sheets)
L = ['# Workbook audit — `MINGA-PARISH -DATA BASE -MIAMALA & RIPOTI ZOTE. system (1).xlsm`', '',
     '_Generated by `tools/migration/build_audit_docs.py` from a structural scan of the workbook (openpyxl; macros not executed). '
     'Values are not reproduced here — the workbook contains personal data and stays out of the repository._', '',
     '## Summary', '',
     f'- **Worksheets:** {len(sheets)} ({sum(1 for s in sheets if s["state"] != "visible")} hidden)',
     f'- **Formulas:** {sum(s["formulas"] for s in sheets):,} in {sum(s["n_families"] for s in sheets):,} distinct formula families',
     f'- **Typed values:** {sum(s["values"] for s in sheets):,}',
     f'- **Named ranges:** {len(inv["defined_names"])} (33 ledger blocks, 51 register blocks, 2 others)',
     f'- **Cached Excel errors:** ' + ', '.join(f'{k} {v:,}' for k, v in sorted(collections.Counter(e for s in sheets for e, n in s['errors'].items() for _ in range(n)).items())),
     f'- **VBA:** `xl/vbaProject.bin` — 5 procedures, presentation only (hide rows containing "-", export one PDF per dropdown value). No calculation, data entry or external calls. Not executed.',
     '- **Classification:** ' + ', '.join(f'{k} {v}' for k, v in cls_count.most_common()), '',
     '## The two source sheets', '',
     'Everything else in the workbook is derived from two sheets:', '',
     '1. **AKAUNTI BOOK-MIAMALA YOTE** — the payment ledger (5,796 amount rows across 2025/2026; 336 without a receipt number). '
     'Reports find a block subtotal with `VLOOKUP(CONCATENATE(purpose," ",jumuiya), \'AKAUNTI BOOK…\'!$E:$O, col)` where col 7 = target (K), 8 = paid 2025 (L), 9 = paid 2026 (M), 10 = balance (N). '
     'This is a hand-built SUMIFS.',
     '2. **PAROKIA DATA BASE** — the register of 862 families / 2,231 people, with the same payments **typed a second time** per person (e.g. `=10000+10000+10000+10000`). '
     'This double entry is the manual work the new system removes: payments are entered once, every view is computed.', '',
     '## Sheet inventory', '',
     '| # | Sheet | State | Used range | Formulas | Values | Merged | Hidden rows | Errors | Class | Purpose |',
     '|---:|---|---|---|---:|---:|---:|---:|---|---|---|']
for i, s in enumerate(sheets, 1):
    c, purpose = classify(s['name'], s)
    errs = ', '.join(f'{k}×{v}' for k, v in s['errors'].items()) or '—'
    L.append(f"| {i} | {s['name'].strip()} | {s['state']} | {s['dims']} | {s['formulas']:,} | {s['values']:,} | {s['merged']:,} | {s['hidden_rows']:,} | {errs} | {c} | {purpose} |")
L += ['', '## Formula families per sheet', '',
      'Functions used and the most frequent formula shapes (cell references normalised). Sheets without formulas are omitted.', '']
for s in sheets:
    if not s['formulas']: continue
    L.append(f"### {s['name'].strip()}")
    L.append(f"- Functions: {', '.join(f'{k} {v:,}' for k, v in s['funcs'].items()) or '—'}")
    L.append(f"- Reads from: {', '.join('`' + x + '`' for x in s['xrefs']) or 'itself only'}")
    if s['err_cells']: L.append(f"- Example errors: {', '.join('`' + e.split(':')[0] + ' ' + e.split(':')[1] + '`' for e in s['err_cells'][:5])}")
    L.append(f"- Main families: {fam_list(s)}")
    L.append('')
os.makedirs(os.path.join(ROOT, 'docs'), exist_ok=True)
open(os.path.join(ROOT, 'docs', 'WORKBOOK_AUDIT.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(L))

# ---------------- dependencies
D = ['# Worksheet dependencies', '', '_Generated from cross-sheet references found in formulas._', '',
     'Arrows read "sheet → sheets it reads from". `REF` means a reference that Excel already shows as `#REF!` (the target was deleted).', '',
     '```mermaid', 'flowchart LR']
ids = {}
def nid(n):
    if n not in ids: ids[n] = f'S{len(ids)}'
    return ids[n]
core = {'AKAUNTI BOOK-MIAMALA YOTE', 'PAROKIA DATA BASE', 'HOMEBOOK', 'HOMEDATA', 'MICHANGO-2026 '}
for s in sheets:
    for x in s['xrefs']:
        if x in core and s['name'] not in core:
            pass
for n in core:
    D.append(f'  {nid(n)}["{n.strip()}"]')
D.append(f'  REPORTS["{sum(1 for s in sheets if s["name"] not in core and s["xrefs"])} report / form sheets"]')
for n in core:
    users = [s for s in sheets if n in s['xrefs'] and s['name'] not in core]
    if users: D.append(f'  REPORTS -->|{len(users)} sheets| {nid(n)}')
for s in sheets:
    if s['name'] in core:
        for x in s['xrefs']:
            if x in core: D.append(f'  {nid(s["name"])} --> {nid(x)}')
D += ['```', '', '| Sheet | Reads from |', '|---|---|']
for s in sheets:
    if s['xrefs']: D.append(f"| {s['name'].strip()} | {', '.join(f'{k} ({v:,})' for k, v in s['xrefs'].items())} |")
broken = [s['name'].strip() for s in sheets if 'REF' in s['xrefs']]
D += ['', f'**Sheets with broken (`#REF!`) references:** {len(broken)} — ' + ', '.join(broken), '',
      '**Defined names** map jumuiya blocks: 33 on the ledger (e.g. `CLARA_` = rows 750–1667) and 51 on the register '
      '(e.g. `CLARA` = rows 2758–2856). The importer uses these names, not row guesses — see `tools/migration/mapping.json`.']
open(os.path.join(ROOT, 'docs', 'WORKSHEET_DEPENDENCIES.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(D))
print('ok', len(sheets))
