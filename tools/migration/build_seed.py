"""
Generate database/migrations/20261015_06_reference_seed.sql from mapping.json.

    python -I tools/migration/build_seed.py

The seed holds only parish identity, structure (vigango, jumuiya, groups),
categories, funds, accounts, financial years and campaigns — no personal data,
so the generated file is safe to commit. Re-runnable (upserts by natural key).
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
M = json.load(open(os.path.join(HERE, 'mapping.json'), encoding='utf-8'))
YEARS = [2024, 2025, 2026, 2027]
CAMPAIGN_YEARS = {'MAVUNO': [2024, 2025, 2026, 2027], 'UJENZI': [2024, 2025, 2026, 2027]}


def q(s):
    return 'null' if s is None else "'" + str(s).replace("'", "''") + "'"


def arr(xs):
    return "array[" + ",".join(q(x) for x in xs) + "]::text[]" if xs else "'{}'::text[]"


p = M['parish']
out = [
    '-- ============================================================================',
    '-- Minga Parish Management System — migration 06: reference data (GENERATED)',
    '--   Generated by tools/migration/build_seed.py from tools/migration/mapping.json.',
    '--   Contains no personal data. Re-runnable.',
    '-- ============================================================================',
    '',
    f"insert into public.parishes (code, official_name, short_name, patron_saint, diocese, postal_address, receipt_title, receipt_prefix, verified_fields)",
    f"values ({q(p['code'])}, {q(p['official_name'])}, {q(p['short_name'])}, {q(p['patron_saint'])}, {q(p['diocese'])}, {q(p['postal_address'])}, {q(p['receipt_title'])}, {q(p['code'])},",
    "        array['official_name','diocese','postal_address','patron_saint'])",
    "on conflict (code) do nothing;",
    "",
    "do $seed$",
    "declare v_parish uuid; v_root uuid;",
    "begin",
    f"  select id into v_parish from public.parishes where code = {q(p['code'])};",
    "",
    "  -- organisational tree",
    f"  insert into public.org_units (parish_id, unit_type, name, official_name) values (v_parish, 'parish', {q(p['short_name'])}, {q(p['official_name'])})",
    "    on conflict (parish_id, unit_type, name) do nothing;",
    f"  select id into v_root from public.org_units where parish_id = v_parish and unit_type = 'parish';",
]
for i, k in enumerate(M['kigango'], 1):
    out.append(f"  insert into public.org_units (parish_id, parent_id, unit_type, name, ordinal, zone, legacy_names, notes) values "
               f"(v_parish, v_root, 'kigango', {q(k['name'])}, {i}, {q(k['zone'])}, {arr(k['aliases'])}, {q(k.get('note'))})"
               f" on conflict (parish_id, unit_type, name) do update set legacy_names = excluded.legacy_names, zone = excluded.zone;")
for j in M['jumuiya']:
    aliases = j['aliases'] + [x for x in (j.get('ledger'), j.get('register')) if x]
    out.append(f"  insert into public.org_units (parish_id, parent_id, unit_type, name, ordinal, legacy_names) values "
               f"(v_parish, (select id from public.org_units where parish_id = v_parish and unit_type = 'kigango' and name = {q(j['kigango'])}), "
               f"'jumuiya', {q(j['name'])}, {j['n']}, {arr(aliases)})"
               f" on conflict (parish_id, unit_type, name) do update set legacy_names = excluded.legacy_names, parent_id = excluded.parent_id;")
for g in M['parish_groups']:
    out.append(f"  insert into public.org_units (parish_id, parent_id, unit_type, name, legacy_names) values "
               f"(v_parish, v_root, 'group', {q(g['name'])}, {arr(g['aliases'])})"
               f" on conflict (parish_id, unit_type, name) do update set legacy_names = excluded.legacy_names;")

out += ["", "  -- funds and chart of accounts"]
for f in M['funds']:
    out.append(f"  insert into public.funds (parish_id, code, name, is_restricted) values (v_parish, {q(f['code'])}, {q(f['name'])}, {str(f['restricted']).lower()})"
               f" on conflict (parish_id, code) do update set name = excluded.name, is_restricted = excluded.is_restricted;")
for a in M['accounts']:
    fund = f"(select id from public.funds where parish_id = v_parish and code = {q(a['fund'])})" if a.get('fund') else 'null'
    out.append(f"  insert into public.ledger_accounts (parish_id, code, name, account_type, money_kind, fund_id) values "
               f"(v_parish, {q(a['code'])}, {q(a['name'])}, {q(a['type'])}, {q(a.get('money'))}, {fund})"
               f" on conflict (parish_id, code) do update set name = excluded.name;")

out += ["", "  -- contribution and expense categories"]
ca = M['category_accounts']
for i, c in enumerate(M['categories'], 1):
    kind = c['kind']
    inc = exp = None
    if kind == 'expense':
        exp = ca['by_code'].get(c['code']) or ca['by_fund'].get(c['fund'], {}).get('expense') or ca['expense']
    else:
        inc = ca['by_fund'].get(c['fund'], {}).get('income') or ca[kind]
    acc = lambda code: f"(select id from public.ledger_accounts where parish_id = v_parish and code = {q(code)})" if code else 'null'
    out.append(
        f"  insert into public.contribution_categories (parish_id, code, name_sw, name_en, kind, is_pledgeable, uses_period_month, fund_id, "
        f"income_account_id, expense_account_id, legacy_labels, sort_order) values (v_parish, {q(c['code'])}, {q(c['name_sw'])}, {q(c['name_en'])}, "
        f"{q(kind)}, {str(bool(c.get('pledge'))).lower()}, {str(bool(c.get('period'))).lower()}, "
        f"(select id from public.funds where parish_id = v_parish and code = {q(c['fund'])}), {acc(inc)}, {acc(exp)}, {arr(c['labels'])}, {i * 10})"
        f" on conflict (parish_id, code) do update set name_sw = excluded.name_sw, name_en = excluded.name_en, kind = excluded.kind,"
        f" is_pledgeable = excluded.is_pledgeable, uses_period_month = excluded.uses_period_month, fund_id = excluded.fund_id,"
        f" income_account_id = excluded.income_account_id, expense_account_id = excluded.expense_account_id, legacy_labels = excluded.legacy_labels;")

out += ["", "  -- financial years (calendar years, as in the workbook's KIASI-2025 / KIASI-2026 columns)"]
for y in YEARS:
    out.append(f"  insert into public.financial_years (parish_id, label, starts_on, ends_on) values (v_parish, '{y}', '{y}-01-01', '{y}-12-31')"
               f" on conflict (parish_id, label) do nothing;")
out.append("  perform public.ensure_periods(id) from public.financial_years where parish_id = v_parish;")

out += ["", "  -- campaigns for pledge-based categories"]
for c in M['categories']:
    if not c.get('pledge'): continue
    for y in CAMPAIGN_YEARS.get(c['code'], [2025, 2026]):
        out.append(
            f"  insert into public.campaigns (parish_id, category_id, financial_year_id, campaign_year, name, starts_on, ends_on, recurs_annually) "
            f"select v_parish, c.id, (select id from public.financial_years where parish_id = v_parish and label = '{y}'), {y}, "
            f"{q(c['name_sw'] + ' ' + str(y))}, '{y}-01-01', '{y}-12-31', true from public.contribution_categories c "
            f"where c.parish_id = v_parish and c.code = {q(c['code'])} on conflict (parish_id, category_id, campaign_year, name) do nothing;")

out += ["", "  -- leadership positions"]
for code, sw, en, lvl, so in [
    ('PAROKO', 'Paroko', 'Parish Priest', 'parish', 10), ('PAROKO_MSAIDIZI', 'Paroko Msaidizi', 'Assistant Priest', 'parish', 20),
    ('KATEKISTA', 'Katekista', 'Catechist', 'parish', 30), ('KATIBU_PAROKIA', 'Katibu wa Parokia', 'Parish Secretary', 'parish', 40),
    ('MHAZINI_PAROKIA', 'Mhazini wa Parokia', 'Parish Treasurer', 'parish', 50), ('MHASIBU_PAROKIA', 'Mhasibu wa Parokia', 'Parish Accountant', 'parish', 60),
    ('MWENYEKITI_PAROKIA', 'Mwenyekiti wa Halmashauri ya Parokia', 'Parish Council Chair', 'parish', 70),
    ('MWENYEKITI_KIGANGO', 'Mwenyekiti wa Kigango', 'Kigango Chair', 'kigango', 110), ('KATIBU_KIGANGO', 'Katibu wa Kigango', 'Kigango Secretary', 'kigango', 120),
    ('MHAZINI_KIGANGO', 'Mhazini wa Kigango', 'Kigango Treasurer', 'kigango', 130),
    ('MWENYEKITI_JUMUIYA', 'Mwenyekiti wa Jumuiya', 'Jumuiya Chair', 'jumuiya', 210), ('KATIBU_JUMUIYA', 'Katibu wa Jumuiya', 'Jumuiya Secretary', 'jumuiya', 220),
    ('MHAZINI_JUMUIYA', 'Mhazini wa Jumuiya', 'Jumuiya Treasurer', 'jumuiya', 230), ('KIONGOZI_CHAMA', 'Kiongozi wa Chama/Kikundi', 'Group Leader', 'group', 310)]:
    out.append(f"  insert into public.leadership_positions (code, title_sw, title_en, level, sort_order) values ({q(code)}, {q(sw)}, {q(en)}, {q(lvl)}, {so}) on conflict (code) do nothing;")

out += ["end", "$seed$;", ""]
path = os.path.join(ROOT, 'database', 'migrations', '20261015_06_reference_seed.sql')
open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('wrote', path, len(out), 'lines')
